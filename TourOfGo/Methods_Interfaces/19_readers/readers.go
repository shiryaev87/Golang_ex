package main

import "golang.org/x/tour/reader"

// Создаем пустую структуру
type MyReader struct{}

// РЕШЕНИЕ: Реализуем метод Read, чтобы MyReader стал удовлетворять интерфейсу io.Reader
func (r MyReader) Read(b []byte) (int, error) {
	// Проходим циклом по всему переданному срезу (буферу)
	for i := range b {
		// Записываем в каждую ячейку код символа 'A' (в Go это байт)
		b[i] = 'A'
	}

	// Метод должен вернуть количество успешно прочитанных/записанных байт.
	// Так как мы заполнили весь срез, возвращаем его длину.
	// Ошибку возвращаем nil, так как наш поток бесконечный (io.EOF не наступает).
	return len(b), nil
}

func main() {
	// Функция Validate внутри пакета reader протестирует ваш код:
	// она передаст буфер, вызовет Read() и проверит,
	// заполнился ли он правильным количеством букв 'A'.
	reader.Validate(MyReader{})
}
